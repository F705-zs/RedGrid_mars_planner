"""Formal interfaces (the 'puzzle shapes'). Every repository and provider must have these methods.

They are checked when the app starts (redgrid.registry.verify), so a replacement class with a missing or misnamed
method stops the app at launch with a clear message, instead of failing in the middle of a request.
Signatures are documented here; the startup check verifies that every method exists and is callable.
"""
from __future__ import annotations

from typing import Protocol, runtime_checkable


# ------------------------------------------------------------------ repositories
@runtime_checkable
class RegionRepositoryI(Protocol):
    def get_all(self): ...
    def get_by_id(self, region_id: int): ...
    def set_routable_geometry(self, region_id: int, geometry: dict) -> None: ...


@runtime_checkable
class DatasetRepositoryI(Protocol):
    def get_all(self): ...
    def get_by_region(self, region_id: int): ...
    def get_by_id(self, dataset_id: int): ...
    def get_training_sources(self, model_id: int): ...
    def set_accessed_on(self, url: str, date: str) -> int: ...


@runtime_checkable
class LayerRepositoryI(Protocol):
    def get_by_region(self, region_id: int): ...
    def get_by_key(self, region_id: int, key: str): ...
    def get_features(self, region_id: int, layer_key: str): ...
    def get_features_by_type(self, region_id: int, feature_type: str): ...
    def get_refill_points(self, region_id: int): ...
    def replace_features(self, layer_id: int, features: list) -> int: ...


@runtime_checkable
class ConstantRepositoryI(Protocol):
    def get_all(self): ...
    def get(self, key: str): ...
    def value(self, key: str) -> float: ...


@runtime_checkable
class CostModelRepositoryI(Protocol):
    def get_active(self): ...
    def get_by_id(self, model_id: int, with_weights: bool = True): ...
    def get_by_version(self, version: int): ...
    def get_all(self): ...
    def get_weights(self, model_id: int): ...
    def get_categories(self): ...
    def save(self, model, weights): ...
    def activate(self, model_id: int) -> None: ...


@runtime_checkable
class RouteProfileRepositoryI(Protocol):
    def get_all(self): ...
    def get_by_key(self, key: str): ...
    def get_rules(self, route_type: str): ...


@runtime_checkable
class PriorityPresetRepositoryI(Protocol):
    def get_all(self): ...
    def get_by_key(self, key: str): ...


@runtime_checkable
class TerrainClassRepositoryI(Protocol):
    def get_all(self): ...
    def class_of(self, unit_symbol: str): ...


@runtime_checkable
class EnvironmentRepositoryI(Protocol):
    def get_demo_window(self): ...
    def get_snapshot(self, region_id: int): ...
    def set_demo_window(self, window: dict) -> None: ...
    def replace_observations(self, region_id: int, rows: list) -> int: ...


@runtime_checkable
class MissionRepositoryI(Protocol):
    def get_all(self, status=None): ...
    def get_by_id(self, mission_id: int): ...
    def add(self, mission) -> int: ...
    def update(self, mission) -> None: ...
    def save_priorities(self, mission_id: int, priorities) -> None: ...
    def get_mix(self, mission_id: int): ...
    def save_mix(self, mission_id: int, mix) -> None: ...
    def save_selected_route(self, mission_id: int, route_id) -> None: ...
    def get_annotations(self, mission_id: int): ...
    def add_annotation(self, annotation): ...
    def delete_annotation(self, mission_id: int, annotation_id: int) -> None: ...


@runtime_checkable
class RouteRepositoryI(Protocol):
    def replace_all(self, mission_id: int, routes: list): ...
    def get_by_mission(self, mission_id: int): ...
    def get_by_id(self, route_id: int): ...


@runtime_checkable
class ResourceRepositoryI(Protocol):
    def get_current(self, mission_id: int): ...
    def add_reading(self, mission_id, variable, value, unit, observed_at, source="USER_INPUT", data_state="LATEST_OBSERVATION"): ...
    def copy(self, from_mission: int, to_mission: int) -> None: ...


@runtime_checkable
class RasterRepositoryI(Protocol):
    def path(self, region_id: int, layer_key: str): ...
    def has(self, region_id: int, layer_key: str) -> bool: ...
    def base_grid(self, region_id: int): ...
    def window_grid(self, region_id: int, bbox): ...
    def load_window(self, region_id: int, layer_key: str, grid): ...
    def sample(self, region_id: int, layer_key: str, lon: float, lat: float): ...
    def load_preview(self, region_id: int, layer_key: str, bbox, max_size: int, categorical: bool = False): ...


# ------------------------------------------------------------------ provider contracts (RedGrid Class Specification, Part 2)
